/**
 * Generates TypeScript type definitions from the Frozen Foundation OpenAPI contract.
 *
 * Source: docs/contracts/foundation.openapi.yaml
 * Output: frontend/src/contracts/generated/foundation.ts
 */

import { promises as fs } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import openapiTS, { astToString } from "openapi-typescript";

const SPEC_RELATIVE_PATH = "../../docs/contracts/foundation.openapi.yaml";
const OUTPUT_RELATIVE_PATH = "../src/contracts/generated/foundation.ts";

export async function generateContractProjection() {
  const specUrl = new URL(SPEC_RELATIVE_PATH, import.meta.url);
  const ast = await openapiTS(specUrl);
  const rawTs = astToString(ast);

  const header = `/**
 * AUTO-GENERATED.
 * DO NOT EDIT MANUALLY.
 * Source: docs/contracts/foundation.openapi.yaml
 *
 * Generated by openapi-typescript 7.13.0
 */

`;

  const content = (header + rawTs).replace(/\r\n/g, "\n");
  return content.endsWith("\n") ? content : content + "\n";
}

async function main() {
  try {
    const outputUrl = new URL(OUTPUT_RELATIVE_PATH, import.meta.url);
    const outputPath = fileURLToPath(outputUrl);

    console.log("Generating contract projection from docs/contracts/foundation.openapi.yaml...");
    const content = await generateContractProjection();

    await fs.mkdir(path.dirname(outputPath), { recursive: true });
    await fs.writeFile(outputPath, content, "utf8");

    console.log(`Contract projection generated successfully: ${path.normalize(outputPath)}`);
  } catch (err) {
    console.error("Failed to generate contract projection:", err);
    process.exit(1);
  }
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  main();
}
